package resources.exectests;

import mc.fenix.functiondisplay.functionstructure4fenix.Channel4Display;
import mc.fenix.functiondisplay.functionstructure4fenix.Channel4DisplayBuilder;
import mc.fenix.functiondisplay.functionstructure4fenix.Function4Display;
import mc.fenix.functiondisplay.functionstructure4fenix.Function4DisplayBuilder;
import mc.fenix.functiondisplay.functionstructure4fenix.Function4DisplayDeSer;
import mc.fenix.functiondisplay.functionstructure4fenix.FunctionStructure4FenixDeSer;
import mc.fenix.functiondisplay.functionstructure4fenix.Port4Display;
import mc.fenix.functiondisplay.functionstructure4fenix.Port4DisplayBuilder;
import umlp.backendrte.common.BaseClassObjectMapper;
import util.JSweetTest;

import java.util.Optional;

/**
 * Bidirectional associations of the generated {@code <<pojoCD>>} FunctionStructure4Fenix classes
 * (umlp-rte/frontend/functiondisplay) and their graph-aware JSON round trip ($id/$ref).
 * The TypeScript side runs the classes generated by gui2java2ts against the real commonj2ts.
 */
public class FunctionDisplayGraphRuntimeCheck {

  private static final String TYPE = "mc.fenix.functiondisplay.functionstructure4fenix.Function4Display";

  private static Function4Display createGraph() {
    BaseClassObjectMapper.addDeSers(FunctionStructure4FenixDeSer.getInstance().getDeSerMap());
    Function4Display root = new Function4DisplayBuilder().name("root").build().get();
    Function4Display child = new Function4DisplayBuilder().name("child").build().get();
    child.setOwner(Optional.of(root));
    Channel4Display channel = new Channel4DisplayBuilder().build().get();
    Port4Display input = new Port4DisplayBuilder().name("in").channel4Display(channel).build().get();
    Port4Display output = new Port4DisplayBuilder().name("out").channel4Display(channel).build().get();
    root.addIn(input);
    child.addOut(output);
    return root;
  }

  private static String describe(Function4Display root) {
    Function4Display child = root.getSubFunction(0);
    Port4Display input = root.getIn(0);
    Port4Display output = child.getOut(0);
    return "subFunctions=" + root.sizeSubFunction()
        + " childOwner=" + (child.getOwner().get() == root)
        + " rootOwner=" + root.getOwner().isPresent()
        + " inOwner=" + (input.getOwnerIn().get() == root)
        + " outOwner=" + (output.getOwnerOut().get() == child)
        + " sharedChannel=" + (input.getChannel4Display() == output.getChannel4Display())
        + " channelPorts=" + input.getChannel4Display().sizePort4Display();
  }

  @JSweetTest
  public static String reverseLinks() {
    Function4Display root = createGraph();
    Function4Display child = root.getSubFunction(0);
    String before = describe(root);
    child.setOwner(Optional.empty());
    return before + " afterUnlink=" + root.sizeSubFunction() + "/" + child.getOwner().isPresent();
  }

  @JSweetTest
  public static String jsonRoundTrip() {
    Function4Display root = createGraph();
    String json = BaseClassObjectMapper.serialize(root, TYPE).get();
    Function4Display copy = BaseClassObjectMapper.<Function4Display>deserialize(json, TYPE).get();
    // nested objects must be JSON objects, not quoted JSON strings
    return "refs=" + json.contains("\"$ref\"")
        + " escapedJson=" + json.contains("\\\"")
        + " copied=" + (copy != root)
        + " " + describe(copy);
  }

  @JSweetTest
  public static String independentReads() {
    String json = BaseClassObjectMapper.serialize(createGraph(), TYPE).get();
    Function4Display a = BaseClassObjectMapper.<Function4Display>deserialize(json, TYPE).get();
    Function4Display b = BaseClassObjectMapper.<Function4Display>deserialize(json, TYPE).get();
    return "distinct=" + (a != b)
        + " a=" + (a.getSubFunction(0).getOwner().get() == a)
        + " b=" + (b.getSubFunction(0).getOwner().get() == b);
  }

  @JSweetTest
  public static String failedReadDoesNotRetainIdentities() {
    String json = BaseClassObjectMapper.serialize(createGraph(), TYPE).get();
    String rejected;
    try {
      new Function4DisplayDeSer().deserialize("{\"$ref\":\"missing\"}");
      rejected = "no";
    } catch (Exception e) {
      rejected = "yes";
    }
    return "rejected=" + rejected + " " + describe(new Function4DisplayDeSer().deserialize(json).get());
  }
}
