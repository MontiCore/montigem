/** Tests the DeSers generated by the POJO CD generator for <<pojoCD>> classes */
class PojoDeSerTest {
  private final GemBarChartDataDeSer barDeSer = new GemBarChartDataDeSer();
  private final GemSunburstDataDeSer sunburstDeSer = new GemSunburstDataDeSer();
  private Map<String, DeSer> previousDeSers;

  @BeforeEach
  void registerGeneratedDeSers() {
    previousDeSers = new HashMap<>(BaseClassObjectMapper.getInstance().getBaseDeSers());
    BaseClassObjectMapper.addDeSers(GemBarChartTypesDeSer.getInstance().getDeSerMap());
    BaseClassObjectMapper.addDeSers(GemSunburstChartTypesDeSer.getInstance().getDeSerMap());
    BaseClassObjectMapper.addDeSers(GemTimeSeriesChartTypesDeSer.getInstance().getDeSerMap());
  }

  @AfterEach
  void restoreDeSers() {
    Map<String, DeSer> registered = BaseClassObjectMapper.getInstance().getBaseDeSers();
    registered.clear();
    registered.putAll(previousDeSers);
  }

  @Test
  void roundTripsNestedListsAndOptionalFields() {
    GemBarChartEntry entry = new GemBarChartEntryBuilder()
        .label(Optional.of("Revenue"))
        .stack(Optional.of("total"))
        .data(List.of(-2, 0, 42))
        .backgroundColor(Optional.of("#123456"))
        .hoverBackgroundColor(Optional.empty())
        .build().orElseThrow();
    GemBarChartData original = new GemBarChartDataBuilder()
        .entries(List.of(entry)).labels(List.of("Jan", "Feb", "Mar"))
        .build().orElseThrow();

    String json = barDeSer.serialize(original);
    JsonObject wire = JsonParser.parse(json).getAsJsonObject();
    assertEquals("0", wire.getStringMember("$id"));
    assertEquals("1", wire.getArrayMember("entries").get(0).getAsJsonObject().getStringMember("$id"));
    assertFalse(wire.getArrayMember("entries").get(0).getAsJsonObject().hasMember("hoverBackgroundColor"));

    GemBarChartData restored = barDeSer.deserialize(json).orElseThrow();
    assertNotSame(original, restored);
    assertEquals(original.getLabelsList(), restored.getLabelsList());
    GemBarChartEntry restoredEntry = restored.getEntries(0);
    assertEquals(entry.getLabel(), restoredEntry.getLabel());
    assertEquals(entry.getStack(), restoredEntry.getStack());
    assertEquals(entry.getDataList(), restoredEntry.getDataList());
    assertEquals(entry.getBackgroundColor(), restoredEntry.getBackgroundColor());
    assertEquals(Optional.empty(), restoredEntry.getHoverBackgroundColor());
    assertTrue(restored.build().isPresent());
    assertTrue(restoredEntry.build().isPresent());
  }

  @Test
  void roundTripsEmptyListsAndAbsentOptionals() {
    GemBarChartEntry entry = new GemBarChartEntryBuilder().data(List.of()).build().orElseThrow();
    GemBarChartData original = new GemBarChartDataBuilder()
        .entries(List.of(entry)).labels(List.of()).build().orElseThrow();
    GemBarChartData restored = barDeSer.deserialize(barDeSer.serialize(original)).orElseThrow();
    assertTrue(restored.getLabelsList().isEmpty());
    assertTrue(restored.getEntries(0).getDataList().isEmpty());
    assertEquals(Optional.empty(), restored.getEntries(0).getLabel());
    assertEquals(Optional.empty(), restored.getEntries(0).getStack());
    assertEquals(Optional.empty(), restored.getEntries(0).getBackgroundColor());
  }

  @Test
  void escapesStringsInGeneratedFields() {
    String label = "A \"quote\", a \\slash\nnext line\tand ä";
    GemBarChartData original = new GemBarChartDataBuilder()
        .entries(List.of(new GemBarChartEntryBuilder().label(Optional.of(label))
            .data(List.of(1)).build().orElseThrow()))
        .labels(List.of(label)).build().orElseThrow();
    GemBarChartData restored = barDeSer.deserialize(barDeSer.serialize(original)).orElseThrow();
    assertEquals(label, restored.getLabels(0));
    assertEquals(Optional.of(label), restored.getEntries(0).getLabel());
  }

  @Test
  void roundTripsDatesThroughBaseClassMapper() {
    LocalDateTime timestamp = LocalDateTime.of(2026, 9, 30, 14, 15, 16);
    TimeSeriesDataPoint point = new TimeSeriesDataPointBuilder()
        .timestamp(timestamp).value(-12.5).build().orElseThrow();
    TimeSeries series = new TimeSeriesBuilder().identifier(7L).name("Temperature")
        .color(Optional.of("red")).hidden(true).deactivated(false)
        .datapoints(List.of(point)).build().orElseThrow();
    TimeSeriesEvent event = new TimeSeriesEventBuilder().timestamp(timestamp).name("Start")
        .textColor(Optional.empty()).backgroundColor(Optional.of("blue"))
        .show(true).build().orElseThrow();
    TimeSeriesData original = new TimeSeriesDataBuilder()
        .series(List.of(series)).events(List.of(event)).build().orElseThrow();
    TimeSeriesDataDeSer deser = new TimeSeriesDataDeSer();

    String json = BaseClassObjectMapper.serialize(original, deser.getTypeIdentifier()).orElseThrow();
    TimeSeriesData restored = BaseClassObjectMapper.<TimeSeriesData>deserialize(
        json, deser.getTypeIdentifier()).orElseThrow();
    assertEquals(7L, restored.getSeries(0).getIdentifier());
    assertEquals("Temperature", restored.getSeries(0).getName());
    assertEquals(Optional.of("red"), restored.getSeries(0).getColor());
    assertTrue(restored.getSeries(0).isHidden());
    assertFalse(restored.getSeries(0).isDeactivated());
    assertEquals(timestamp, restored.getSeries(0).getDatapoints(0).getTimestamp());
    assertEquals(-12.5, restored.getSeries(0).getDatapoints(0).getValue());
    assertEquals(timestamp, restored.getEvents(0).getTimestamp());
    assertEquals("Start", restored.getEvents(0).getName());
    assertEquals(Optional.empty(), restored.getEvents(0).getTextColor());
    assertEquals(Optional.of("blue"), restored.getEvents(0).getBackgroundColor());
    assertTrue(restored.getEvents(0).isShow());
  }

  @Test
  void preservesSharedReferences() {
    GemSunburstData child = node("child", 2);
    GemSunburstData root = node("root", 1);
    root.addSubEntries(child);
    root.addSubEntries(child);
    String json = sunburstDeSer.serialize(root);
    JsonObject secondChild = JsonParser.parse(json).getAsJsonObject()
        .getArrayMember("subEntries").get(1).getAsJsonObject();
    assertTrue(secondChild.hasMember("$ref"));
    assertFalse(secondChild.hasMember("$id"));

    GemSunburstData restored = sunburstDeSer.deserialize(json).orElseThrow();
    assertSame(restored.getSubEntries(0), restored.getSubEntries(1));
    assertEquals("child", restored.getSubEntries(0).getEntry().getLabel());
  }

  @Test
  void keepsDistinctObjectsWithEqualValuesDistinct() {
    GemSunburstData root = node("root", 1);
    root.addSubEntries(node("same", 2));
    root.addSubEntries(node("same", 2));
    GemSunburstData restored = sunburstDeSer.deserialize(sunburstDeSer.serialize(root)).orElseThrow();
    assertNotSame(restored.getSubEntries(0), restored.getSubEntries(1));
    assertNotSame(restored.getSubEntries(0).getEntry(), restored.getSubEntries(1).getEntry());
    assertEquals(restored.getSubEntries(0).getEntry().getLabel(),
        restored.getSubEntries(1).getEntry().getLabel());
  }

  @Test
  void roundTripsSelfCycle() {
    GemSunburstData root = node("root", 1);
    root.addSubEntries(root);
    GemSunburstData restored = sunburstDeSer.deserialize(sunburstDeSer.serialize(root)).orElseThrow();
    assertSame(restored, restored.getSubEntries(0));
    assertTrue(restored.build().isPresent());
  }

  @Test
  void roundTripsMutualCycle() {
    GemSunburstData root = node("root", 1);
    GemSunburstData child = node("child", 2);
    root.addSubEntries(child);
    child.addSubEntries(root);
    GemSunburstData restored = sunburstDeSer.deserialize(sunburstDeSer.serialize(root)).orElseThrow();
    assertSame(restored, restored.getSubEntries(0).getSubEntries(0));
    assertEquals("child", restored.getSubEntries(0).getEntry().getLabel());
    assertTrue(restored.getSubEntries(0).build().isPresent());
  }

  @Test
  void readsLegacyJsonWithoutIdentityMarkers() {
    GemSunburstData restored = sunburstDeSer.deserialize(
        "{\"entry\":{\"label\":\"root\",\"value\":1},\"subEntries\":["
            + "{\"entry\":{\"label\":\"child\",\"value\":2},\"subEntries\":[]}]}")
        .orElseThrow();
    assertEquals("root", restored.getEntry().getLabel());
    assertEquals(1, restored.getEntry().getValue());
    assertEquals("child", restored.getSubEntries(0).getEntry().getLabel());
    assertTrue(restored.getSubEntries(0).getSubEntriesList().isEmpty());
  }

  @Test
  void supportsJsonDeSerEntryPoints() {
    GemSunburstData original = node("root", 1);
    original.addSubEntries(original);
    JsonPrinter printer = new JsonPrinter(true);
    printer.beginObject();
    sunburstDeSer.buildJson(original, printer);
    printer.endObject();
    GemSunburstData restored = sunburstDeSer.fromJson(JsonParser.parse(printer.getContent())).orElseThrow();
    assertSame(restored, restored.getSubEntries(0));
    assertEquals("root", restored.getEntry().getLabel());
  }

  @Test
  void rejectsUnknownReferences() {
    assertThrows(IllegalArgumentException.class,
        () -> sunburstDeSer.deserialize("{\"$ref\":\"missing\"}"));
  }

  @Test
  void rejectsDuplicateIdentities() {
    assertThrows(IllegalArgumentException.class, () -> sunburstDeSer.deserialize(
        "{\"$id\":\"0\",\"entry\":{\"$id\":\"0\",\"label\":\"root\",\"value\":1},\"subEntries\":[]}"));
  }

  @Test
  void rejectsReferencesToWrongPojoType() {
    // The entry field expects GemSunburstEntry, but id 0 denotes GemSunburstData.
    assertThrows(IllegalArgumentException.class, () -> sunburstDeSer.deserialize(
        "{\"$id\":\"0\",\"entry\":{\"$ref\":\"0\"},\"subEntries\":[]}"));
  }

  @Test
  void rejectsReferenceWithDefinitionMarker() {
    assertThrows(IllegalArgumentException.class, () -> sunburstDeSer.deserialize(
        "{\"$id\":\"0\",\"entry\":{\"label\":\"root\",\"value\":1},"
            + "\"subEntries\":[{\"$ref\":\"0\",\"$id\":\"1\"}]}"));
  }

  @Test
  void resetsContextBetweenGraphsAndAfterFailure() {
    PojoGraphContext context = new PojoGraphContext();
    GemSunburstData original = node("root", 1);
    String first = context.serializeObject(original, sunburstDeSer);
    String second = context.serializeObject(original, sunburstDeSer);
    assertEquals(first, second);
    JsonObject json = JsonParser.parse(first).getAsJsonObject();
    GemSunburstData firstRead = (GemSunburstData) context.deserializeObject(json, sunburstDeSer).orElseThrow();
    GemSunburstData secondRead = (GemSunburstData) context.deserializeObject(json, sunburstDeSer).orElseThrow();
    assertNotSame(firstRead, secondRead);
    assertThrows(IllegalArgumentException.class, () -> context.deserializeObject(
        JsonParser.parse("{\"$id\":\"0\",\"entry\":{\"$ref\":\"missing\"}}").getAsJsonObject(), sunburstDeSer));
    GemSunburstData afterFailure = (GemSunburstData) context.deserializeObject(json, sunburstDeSer).orElseThrow();
    assertEquals("root", afterFailure.getEntry().getLabel());
    assertNotSame(firstRead, afterFailure);
  }

  private GemSunburstData node(String label, int value) {
    return new GemSunburstDataBuilder()
        .entry(new GemSunburstEntryBuilder().label(label).value(value).build().orElseThrow())
        .subEntries(new ArrayList<>()).build().orElseThrow();
  }
}
