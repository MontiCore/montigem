  /** URL of the component's page in the generated online documentation. */
  public static String docUrl(String component) {
    String pkg = packageOf(component);
    if (pkg.isEmpty()) {
      return DOC_BASE_URL + "Frontend-RTE.html";
    }
    return DOC_BASE_URL + pkg.replace('.', '/') + "/" + component + ".html";
  }
