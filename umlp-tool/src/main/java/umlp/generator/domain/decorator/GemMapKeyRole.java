package umlp.generator.domain.decorator;

import de.monticore.cd._symboltable.CDSymbolTables;
import de.monticore.cdassociation._ast.ASTCDAssocSide;
import de.monticore.cdbasis._ast.ASTCDClass;
import de.monticore.cdbasis._ast.ASTCDCompilationUnit;
import de.monticore.cdbasis._ast.ASTCDType;
import de.se_rwth.commons.StringTransformations;
import umlp.generator.util.TagLookUp;

import java.util.ArrayList;
import java.util.Collection;
import java.util.HashSet;
import java.util.LinkedHashMap;
import java.util.List;
import java.util.Map;
import java.util.Set;
import java.util.function.Predicate;
import java.util.stream.Stream;

/**
 * A map role declared by a type of a class diagram (attribute qualified association): its values are rekeyed by the
 * managers. The manager of each value class attaches a key observer per role (like its other observers, whenever it
 * takes up or loads an object); the observer asks the manager of the role, which rekeys the maps of the loaded
 * owners, see {@link #getOwners}. Owners that are not loaded derive the keys when their maps are loaded.
 */
public class GemMapKeyRole {

  protected final String declaringType;

  protected final String role;

  // the type of the keys passed on rekeying: long (the gemId of the key object) for GemEntryMaps
  protected final String keyType;

  protected final String valueType;

  protected final List<GemMapOwnerRole> owners;

  public GemMapKeyRole(String declaringType, String role, String keyType, String valueType,
                       List<GemMapOwnerRole> owners) {
    this.declaringType = declaringType;
    this.role = role;
    this.keyType = keyType;
    this.valueType = valueType;
    this.owners = owners;
  }

  /**
   * @return the name of the type that declares the map role (a class, possibly abstract, or an interface)
   */
  public String getDeclaringType() {
    return declaringType;
  }

  public String getRole() {
    return role;
  }

  public String getKeyType() {
    return keyType;
  }

  /**
   * @return the full name of the value type of the map role
   */
  public String getValueType() {
    return valueType;
  }

  /**
   * @return the concrete owner classes holding the map (the declaring type and its concrete subclasses)
   */
  public List<GemMapOwnerRole> getOwners() {
    return owners;
  }

  /**
   * @return the name part of the manager methods that rekey the values of the role, e.g. CourseByLogin
   */
  public String getRekeyName() {
    return declaringType + StringTransformations.capitalize(role);
  }

  /**
   * @return the key observer class for values of type valueClass (generated by GemMapAssocDecorator)
   */
  public String getKeyObserverClass(String valueClass) {
    return GemMapAssocDecorator.getKeyObserverName(declaringType, role, valueClass);
  }

  /**
   * @return the manager attribute holding the key observer for values of type valueClass
   */
  public String getKeyObserverAttribute(String valueClass) {
    return "the" + getKeyObserverClass(valueClass);
  }

  /**
   * the map roles declared by the classes and interfaces of cd
   */
  public static List<GemMapKeyRole> declaredIn(ASTCDCompilationUnit cd) {
    List<GemMapKeyRole> result = new ArrayList<>();
    Stream.concat(cd.getCDDefinition().getCDClassesList().stream(), cd.getCDDefinition().getCDInterfacesList().stream())
        .filter(t -> !t.getModifier().isDerived())
        .forEach(declaring -> CDSymbolTables.getAssociations(declaring).stream()
            .filter(Predicate.not(GenService::isSymbolDerived))
            .filter(GenService::isMap)
            // type qualified maps take their keys on put, they are never rekeyed
            .filter(GenService::isKeyDerived)
            .forEach(side -> result.add(of(cd, declaring, side))));
    return result;
  }

  /**
   * the map roles declared in cd whose values may be objects of the concrete class valueClass, i.e. whose value type
   * is valueClass or one of its supertypes
   */
  public static List<GemMapKeyRole> observing(ASTCDCompilationUnit cd, ASTCDType valueClass) {
    Set<String> valueTypes = new HashSet<>();
    valueTypes.add(valueClass.getSymbol().getFullName());
    CDSymbolTables.getTransitiveSuperTypes(valueClass).forEach(t -> valueTypes.add(t.getSymbol().getFullName()));
    List<GemMapKeyRole> result = new ArrayList<>();
    for (GemMapKeyRole role : declaredIn(cd)) {
      if (valueTypes.contains(role.getValueType())) {
        result.add(role);
      }
    }
    return result;
  }

  /**
   * the manager attributes holding the key observers that the manager attaches to objects of valueClass
   */
  public static List<String> keyObserverAttributes(ASTCDCompilationUnit cd, ASTCDType valueClass) {
    List<String> result = new ArrayList<>();
    for (GemMapKeyRole role : observing(cd, valueClass)) {
      result.add(role.getKeyObserverAttribute(valueClass.getName()));
    }
    return result;
  }

  /**
   * the key observer attributes per type name, see {@link #keyObserverAttributes}
   */
  public static Map<String, List<String>> keyObserverAttributes(ASTCDCompilationUnit cd,
                                                               Collection<? extends ASTCDType> valueClasses) {
    Map<String, List<String>> result = new LinkedHashMap<>();
    for (ASTCDType valueClass : valueClasses) {
      result.put(valueClass.getName(), keyObserverAttributes(cd, valueClass));
    }
    return result;
  }

  protected static GemMapKeyRole of(ASTCDCompilationUnit cd, ASTCDType declaring, ASTCDAssocSide side) {
    QualifierKey key = QualifierKey.of(side);
    List<GemMapOwnerRole> owners = new ArrayList<>();
    for (ASTCDClass owner : cd.getCDDefinition().getCDClassesList()) {
      if (owner.getModifier().isAbstract() || owner.getModifier().isDerived()) {
        continue;
      }
      boolean holds = CDSymbolTables.getAssociationsInHierarchy(owner).stream()
          .anyMatch(s -> s.getName().equals(side.getName())
              && s.getSymbol().getOtherSide().getType().getTypeInfo().getFullName()
              .equals(declaring.getSymbol().getFullName()));
      if (holds) {
        owners.add(new GemMapOwnerRole(owner.getName(), side.getName(), TagLookUp.isSingleton(owner)));
      }
    }
    return new GemMapKeyRole(declaring.getName(), side.getName(), key.isEntryKey() ? "long" : key.getKeyType(),
        side.getSymbol().getType().getTypeInfo().getFullName(), owners);
  }
}
